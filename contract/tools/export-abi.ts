import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const target = resolve(root, '../frontend/src/generated');
mkdirSync(target, { recursive: true });
const contracts = {
  vaultAbi: 'AdaptiveLPVault',
  controlAbi: 'VaultControl',
  oracleAbi: 'CanonicalV3Oracle',
  adapterAbi: 'UniswapV3Adapter',
};
const source = Object.entries(contracts)
  .map(([name, contract]) => {
    const artifact = JSON.parse(
      readFileSync(resolve(root, `out/${contract}.sol/${contract}.json`), 'utf8'),
    );
    return `export const ${name} = ${JSON.stringify(artifact.abi)} as const;`;
  })
  .join('\n');
writeFileSync(
  resolve(target, 'abi.ts'),
  '// Generated by npm run abi. Do not edit.\n' + source + '\n',
);
console.log('已导出 Vault、Control、Oracle 与 Adapter ABI。');
